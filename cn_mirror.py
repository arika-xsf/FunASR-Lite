"""Build a China-mirror requirements file for ``webui.bat cn``.

The shipped requirements*.txt pin ``--extra-index-url`` to download.pytorch.org,
which is often slow or times out from mainland China. This helper copies every
pinned version but replaces only the index lines, so versions stay
single-sourced in requirements*.txt and no tracked file is modified.

A mirror is NOT always faster. Both URLs can be overridden:
  FUNASR_PYPI_INDEX   PyPI index (also used by webui.bat to upgrade pip)
  FUNASR_TORCH_INDEX  PyTorch wheel index for the selected GPU/CPU mode
Unset variables fall back to the Aliyun defaults below.

Usage: python cn_mirror.py <requirements.txt> <output.txt> <GPU|CPU>
"""
import os
import sys
from pathlib import Path

DEFAULT_PYPI = "https://mirrors.aliyun.com/pypi/simple"
DEFAULT_PYTORCH = {
    "GPU": "https://mirrors.aliyun.com/pytorch-wheels/cu128/",
    "CPU": "https://mirrors.aliyun.com/pytorch-wheels/cpu/",
}


def main() -> int:
    if len(sys.argv) != 4:
        print("usage: cn_mirror.py <requirements> <output> <GPU|CPU>", file=sys.stderr)
        return 2
    src = Path(sys.argv[1])
    dst = Path(sys.argv[2])
    mode = sys.argv[3].upper()
    if mode not in DEFAULT_PYTORCH:
        print("mode must be GPU or CPU", file=sys.stderr)
        return 2
    if not src.is_file():
        print("requirements file not found: %s" % src, file=sys.stderr)
        return 2

    pypi = os.environ.get("FUNASR_PYPI_INDEX") or DEFAULT_PYPI
    torch_index = os.environ.get("FUNASR_TORCH_INDEX") or DEFAULT_PYTORCH[mode]
    # webui.bat also forwards FUNASR_PYPI_INDEX to `pip install -i`, so reject
    # anything that could break a Windows command line before writing a file.
    for label, url in (("FUNASR_PYPI_INDEX", pypi), ("FUNASR_TORCH_INDEX", torch_index)):
        if not url.startswith(("http://", "https://")) or any(
                c.isspace() or c in '&|<>^"' for c in url):
            print("invalid %s: %r" % (label, url), file=sys.stderr)
            return 2

    kept = []
    for line in src.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith(("--index-url", "--extra-index-url", "--find-links")):
            continue
        kept.append(line)

    header = [
        "# Generated by cn_mirror.py; source: %s" % src.name,
        "--index-url " + pypi,
        "--find-links " + torch_index,
    ]
    dst.write_text("\n".join(header + kept) + "\n", encoding="utf-8")
    print("[Mirror] wrote %s (%d lines)" % (dst, len(header) + len(kept)))
    print("[Mirror] PyPI    : %s" % pypi)
    print("[Mirror] PyTorch : %s" % torch_index)
    return 0


if __name__ == "__main__":
    sys.exit(main())
